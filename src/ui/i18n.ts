export const t = (l: Lang, k: Key) => STR[l][k];
/** A piece's name; pass its side to use the army's own name for it (a Comanche King is a Chief). */
export const unitName = (l: Lang, u: UnitTypeId, side?: Player) => (side && factionOf(side).names?.[u]?.[l]) || UNITS[l][u];
export const errorText = (l: Lang, e: ErrorCode) => ERRORS[l][e];
export const reasonText = (l: Lang, r: WinReason) => REASONS[l][r];
/** A side is called by the faction it leads. */
export const playerName = (l: Lang, p: Player) => factionOf(p).name[l];

/** Board coordinate like "D5": column letter, row number. */
export const hexName = (h: Hex) => `${String.fromCharCode(65 + h.col)}${h.row + 1}`;

export function logText(l: Lang, e: LogEntry): string {
  const ru = l === 'ru';
  switch (e.kind) {
    case 'roll':
      return ru ? `${e.reroll ? 'переброс' : 'бросок'} ${e.dice.join('+')} = ${e.total}` : `${e.reroll ? 'rerolled' : 'rolled'} ${e.dice.join('+')} = ${e.total}`;
    case 'move':
      return `${unitName(l, e.unit, e.player)} ${hexName(e.from)} → ${hexName(e.to)} (−${e.cost})`;
    case 'attack':
    case 'shoot': {
      const verb = e.kind === 'attack' ? (ru ? 'бьёт' : 'hits') : ru ? 'стреляет в' : 'shoots';
      const end = e.killed ? (ru ? ', убит' : ', killed') + (e.advanced ? (ru ? ', клетка занята' : ', took the hex') : '') : '';
      const back = e.counter ? (ru ? `; копья: −${e.counter}${e.attackerKilled ? ', атакующий погиб' : ''}` : `; spears hit back −${e.counter}${e.attackerKilled ? ', attacker killed' : ''}`) : '';
      const trees = e.covered ? (ru ? ' (за деревьями)' : ' (behind trees)') : '';
      return `${unitName(l, e.unit, e.player)} ${verb} ${unitName(l, e.target, e.player === 'red' ? 'blue' : 'red').toLowerCase()}: −${e.damage} ${t(l, 'hp')}${trees}${end}${back}`;
    }
    case 'endTurn':
      return ru ? 'конец хода' : 'ended turn';
    case 'win':
      return `${playerName(l, e.player)} ${t(l, 'wins')} ${reasonText(l, e.reason)}`;
  }
}
